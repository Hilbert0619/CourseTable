"""Builds the Focus wallpapers from content/wallpapers/sources.json (photos on Unsplash, Unsplash License).

    py -3.12 -I tools/make_wallpapers.py [--sheet PATH]      # needs Pillow and httpx

For each photo: fetch a 1290x2796 portrait crop from Unsplash's image service (the crop centred on the photo, or on
`focus`), check that the original is big enough not to be enlarged, re-encode it as a progressive JPEG without
metadata, and measure its average colour. Writes supabase/wallpapers/<id>.jpg (the files `supabase seed buckets`
uploads to the public bucket `wallpapers`) and the migration with the rows of public.focus_wallpapers. Prints a
report; `--sheet` also saves a contact sheet of the results to look at.
"""
import io
import json
import os
import sys

import httpx
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = os.path.join(ROOT, "content", "wallpapers", "sources.json")
OUT_DIR = os.path.join(ROOT, "supabase", "wallpapers")
MIGRATION = os.path.join(ROOT, "supabase", "migrations", "20261016100100_focus_wallpapers_unsplash.sql")
WIDTH, HEIGHT = 1290, 2796  # the largest iPhone screens, in pixels
QUALITY = 80


def sql(text):
    return "'" + text.replace("'", "''") + "'"


def fetch(client, url):
    for attempt in range(3):
        try:
            response = client.get(url)
            response.raise_for_status()
            return response
        except httpx.HTTPError as error:
            if attempt == 2:
                sys.exit(f"{url}: {error}")


def build(client, item):
    base = f"https://images.unsplash.com/{item['photo']}"
    meta = fetch(client, base + "?fm=json").json()
    original = (int(meta["PixelWidth"]), int(meta["PixelHeight"]))
    scale = max(WIDTH / original[0], HEIGHT / original[1])
    if scale > 1:
        sys.exit(f"{item['id']}: the original {original[0]}x{original[1]} is too small for {WIDTH}x{HEIGHT}")
    params = f"?w={WIDTH}&h={HEIGHT}&fit=crop&fm=jpg&q=92"
    if "focus" in item:
        params += f"&crop=focalpoint&fp-x={item['focus'][0]}&fp-y={item['focus'][1]}"
    image = Image.open(io.BytesIO(fetch(client, base + params).content))
    image.load()
    if image.size != (WIDTH, HEIGHT):
        sys.exit(f"{item['id']}: got {image.size[0]}x{image.size[1]}")
    image = image.convert("RGB")
    out = io.BytesIO()
    image.save(out, "JPEG", quality=QUALITY, optimize=True, progressive=True, subsampling="4:2:0")
    data = out.getvalue()
    with open(os.path.join(OUT_DIR, f"{item['id']}.jpg"), "wb") as file:
        file.write(data)
    r, g, b = image.resize((1, 1), Image.BOX).getpixel((0, 0))
    return {"image": image, "bytes": len(data), "color": f"#{r:02x}{g:02x}{b:02x}", "original": original}


def main():
    sources = json.load(open(SOURCES, encoding="utf-8"))
    os.makedirs(OUT_DIR, exist_ok=True)
    wanted = {f"{item['id']}.jpg" for item in sources["wallpapers"]}
    for name in os.listdir(OUT_DIR):
        if name not in wanted:
            os.remove(os.path.join(OUT_DIR, name))
    client = httpx.Client(timeout=60, follow_redirects=True)
    rows, built = [], []
    for item in sources["wallpapers"]:
        result = build(client, item)
        built.append((item, result))
        print(f"{item['id']:18} {result['original'][0]}x{result['original'][1]:<6} {result['bytes'] // 1024:5} KB  {result['color']}")
        rows.append("  (" + ", ".join([
            sql(item["id"]), sql(sources["base_url"] + item["id"] + ".jpg"), str(WIDTH), str(HEIGHT), sql(result["color"]),
            str(item.get("focus_y", 0.5)), sql(item["author"]), sql(f"https://unsplash.com/@{item['username']}"),
            sql(f"https://unsplash.com/photos/{item['page']}"), sql(sources["licence"]),
        ]) + ")")
    total = sum(result["bytes"] for _, result in built)
    print(f"{len(built)} wallpapers, {total / 1e6:.1f} MB")

    with open(MIGRATION, "w", encoding="utf-8", newline="\n") as file:
        file.write("-- Generated by tools/make_wallpapers.py from content/wallpapers/sources.json. Do not edit by hand.\n")
        file.write("-- Photos from Unsplash (https://unsplash.com), free to use under the Unsplash License; the image\n")
        file.write("-- files are in supabase/wallpapers/ and go to the Storage bucket `wallpapers` (supabase seed buckets).\n\n")
        file.write("insert into public.focus_wallpapers (id, url, width, height, color, focus_y, author, author_url, source_url, licence)\nvalues\n")
        file.write(",\n".join(rows))
        file.write("\non conflict (id) do update set\n")
        file.write("  url = excluded.url, width = excluded.width, height = excluded.height, color = excluded.color, focus_y = excluded.focus_y,\n")
        file.write("  author = excluded.author, author_url = excluded.author_url, source_url = excluded.source_url,\n")
        file.write("  licence = excluded.licence, active = true;\n")

    with open(os.path.join(os.path.dirname(SOURCES), "SOURCES.md"), "w", encoding="utf-8", newline="\n") as file:
        file.write("# Focus wallpapers — sources\n\n")
        file.write("Generated by `tools/make_wallpapers.py` from `sources.json`. Every picture is a photo from\n")
        file.write("[Unsplash](https://unsplash.com), free to use under the [Unsplash License](https://unsplash.com/license):\n")
        file.write("it may be copied, changed and shown in the app without asking; credit isn't required, but the app shows\n")
        file.write("the photographer's name under each one anyway. The licence of each photo was checked on its page\n")
        file.write("(\"Free to use under the Unsplash License\", not Unsplash+) on 2026-10-16.\n\n")
        file.write(f"Each is cropped to {WIDTH}x{HEIGHT} (portrait) and kept in `supabase/wallpapers/`; the rows of\n")
        file.write("`public.focus_wallpapers` point at the copies in the Storage bucket `wallpapers`.\n\n")
        file.write("| Wallpaper | Photo | By |\n|---|---|---|\n")
        for item, _ in built:
            file.write(f"| `{item['id']}` | [unsplash.com/photos/{item['page']}](https://unsplash.com/photos/{item['page']}) "
                       f"| [{item['author']}](https://unsplash.com/@{item['username']}) |\n")

    if "--sheet" in sys.argv:
        path = sys.argv[sys.argv.index("--sheet") + 1]
        cols, tw, th = 6, 240, 520
        sheet = Image.new("RGB", (cols * (tw + 4), -(-len(built) // cols) * (th + 4)), (17, 17, 17))
        draw = ImageDraw.Draw(sheet)
        font = ImageFont.load_default(18)
        for k, (item, result) in enumerate(built):
            x, y = (k % cols) * (tw + 4), (k // cols) * (th + 4)
            sheet.paste(result["image"].resize((tw, th), Image.LANCZOS), (x, y))
            # The band a 4:5 card shows when it fills its width with the picture, centred on focus_y.
            band = tw * 5 / 4
            top = y + min(max(item.get("focus_y", 0.5) * th - band / 2, 0), th - band)
            draw.rectangle((x, top, x + tw - 1, top + band), outline=(255, 255, 0), width=2)
            draw.rectangle((x, y, x + tw, y + 24), fill=(0, 0, 0))
            draw.text((x + 4, y + 2), item["id"], fill=(255, 255, 255), font=font)
        sheet.save(path, quality=85)
        print("sheet", path)


if __name__ == "__main__":
    main()
