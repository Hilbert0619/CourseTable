"""Writes the Android app's Chinese strings from the iOS translations.

    python tools/xcstrings_to_android.py           # writes android/app/src/main/res/values-zh-rCN/strings.xml
    python tools/xcstrings_to_android.py --check   # only checks that file is complete and up to date (CI)

The English strings are written by hand in android/app/src/main/res/values/strings.xml. Each one's Chinese text is
looked up in Shared/Localizable.xcstrings by its English text (Android's %1$d / %1$s match iOS's %lld / %@), so a
text that the iOS app already shows gets the same translation. Strings that only Android has, or whose Chinese text
must differ on Android, are translated in android/strings-zh.json ({"resource_name": "中文"}, or for <plurals>
{"resource_name": {"other": "中文"}}); those entries win over the catalog. Exits with 1 if a string has no
translation, or (with --check) if the Chinese file would change.
"""
import io
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "Shared", "Localizable.xcstrings")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
ENGLISH = os.path.join(RES, "values", "strings.xml")
CHINESE = os.path.join(RES, "values-zh-rCN", "strings.xml")
OVERRIDES = os.path.join(ROOT, "android", "strings-zh.json")

IOS_SPECIFIER = re.compile(r"%(?:(\d+)\$)?(lld|ld|d|@|lf|f|\.\d+lf|\.\d+f)")
ANDROID_SPECIFIER = re.compile(r"%(?:(\d+)\$)?(d|s|f|\.\d+f)")


def kind(conversion):
    if conversion in ("lld", "ld", "d"):
        return "i"
    if conversion in ("@", "s"):
        return "s"
    return "f"


def normalized(text, specifier):
    """The text with every format specifier replaced by its kind, so iOS and Android texts can be compared."""
    return specifier.sub(lambda m: "{" + kind(m.group(2)) + "}", text)


def android_format(text):
    """An iOS text with Android format specifiers: %lld → %1$d, %@ → %2$s, in order unless already positional."""
    counter = iter(range(1, 100))

    def replace(m):
        position = m.group(1) or str(next(counter))
        conversion = m.group(2)
        if kind(conversion) == "i":
            return f"%{position}$d"
        if kind(conversion) == "s":
            return f"%{position}$s"
        precision = re.match(r"\.\d+", conversion)
        return f"%{position}${precision.group(0) if precision else ''}f"

    return IOS_SPECIFIER.sub(replace, text)


def android_unescape(text):
    text = text.strip() if text else ""
    if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
        text = text[1:-1]
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), text)


def android_escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def catalog_translations():
    catalog = json.load(io.open(CATALOG, encoding="utf-8"))["strings"]
    found = {}
    for key, value in catalog.items():
        unit = value.get("localizations", {}).get("zh-Hans", {}).get("stringUnit")
        if unit and unit.get("value"):
            found[normalized(key, IOS_SPECIFIER)] = unit["value"]
    return found


def main():
    check = "--check" in sys.argv[1:]
    translations = catalog_translations()
    overrides = json.load(io.open(OVERRIDES, encoding="utf-8")) if os.path.exists(OVERRIDES) else {}
    tree = ET.parse(ENGLISH)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/xcstrings_to_android.py from Shared/Localizable.xcstrings and android/strings-zh.json."
        " Don't edit. -->",
        "<resources>",
    ]
    missing = []
    for element in tree.getroot():
        name = element.get("name")
        if element.get("translatable") == "false":
            continue
        if element.tag == "string":
            english = android_unescape(element.text)
            zh = overrides.get(name)
            if zh is None:
                zh = translations.get(normalized(english, ANDROID_SPECIFIER))
                zh = android_format(zh) if zh is not None else None
            if zh is None:
                missing.append(f"{name}: {english}")
                continue
            lines.append(f'    <string name="{name}">{android_escape(zh)}</string>')
        elif element.tag == "plurals":
            items = {item.get("quantity"): android_unescape(item.text) for item in element.findall("item")}
            override = overrides.get(name)
            if override is not None:
                zh = override["other"] if isinstance(override, dict) else override
            else:
                zh = translations.get(normalized(items.get("other", ""), ANDROID_SPECIFIER))
                zh = android_format(zh) if zh is not None else None
            if zh is None:
                missing.append(f"{name} (plural): {items.get('other')}")
                continue
            lines.append(f'    <plurals name="{name}">')
            lines.append(f'        <item quantity="other">{android_escape(zh)}</item>')
            lines.append("    </plurals>")
    lines.append("</resources>")
    output = "\n".join(lines) + "\n"
    unused = sorted(set(overrides) - {element.get("name") for element in tree.getroot()})

    if missing:
        print("No Chinese translation (add it to Shared/Localizable.xcstrings or android/strings-zh.json):")
        for line in missing:
            print("  " + line)
    if unused:
        print("Unused in android/strings-zh.json: " + ", ".join(unused))
    current = io.open(CHINESE, encoding="utf-8").read() if os.path.exists(CHINESE) else None
    if check:
        if current != output:
            print("values-zh-rCN/strings.xml is out of date: run python tools/xcstrings_to_android.py")
            sys.exit(1)
    elif current != output:
        os.makedirs(os.path.dirname(CHINESE), exist_ok=True)
        io.open(CHINESE, "w", encoding="utf-8", newline="\n").write(output)
        print("Wrote " + os.path.relpath(CHINESE, ROOT))
    if missing or unused:
        sys.exit(1)
    count = output.count("<string ") + output.count("<plurals ")
    print(f"{count} Chinese strings, all translated.")


if __name__ == "__main__":
    main()
