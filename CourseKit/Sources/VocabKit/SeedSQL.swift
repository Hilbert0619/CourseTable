import Foundation

/// A system book: a word list shipped by the backend (docs/vocabulary-spec.md §4).
public struct SystemBook: Hashable, Sendable {
    public var id: UUID
    /// Key for stable entry ids: entry `headword` of this book gets `md5("<slug>/<headword>")` as its id.
    public var slug: String
    public var name: String
    public var description: String
    public var source: String
    public var licence: String

    /// 考研词汇: the ECDICT entries tagged `ky`, most frequent first.
    public static let kaoyan = SystemBook(
        id: UUID(uuidString: "00000000-0000-4000-8000-000000000001")!,
        slug: "kaoyan-ecdict",
        name: "考研词汇 (ECDICT)",
        description: "考研英语词汇（ECDICT 中标注为 ky 的词条），按常用程度排序，常用词在前。数据来自 ECDICT（MIT 许可）。",
        source: "ECDICT https://github.com/skywind3000/ECDICT",
        licence: "MIT"
    )
}

/// Writes the SQL that loads a word list into Postgres: the dictionary rows, the system book and its
/// entries. Re-running it updates rows in place, so a changed list can ship as a new migration.
public enum SeedSQL {
    public static let batchSize = 500

    public static func migration(for book: SystemBook, entries: [WordEntry]) -> String {
        var sql = """
        -- Generated by `vocab-content sql` from content/\(book.slug).csv. Do not edit by hand.
        -- Word data: ECDICT (https://github.com/skywind3000/ECDICT), MIT License.

        insert into public.books (id, owner_id, name, description, source, licence, word_count, updated_at)
        values (\(literal(book.id.uuidString.lowercased()))::uuid, null, \(literal(book.name)), \(literal(book.description)),
                \(literal(book.source)), \(literal(book.licence)), \(entries.count), now())
        on conflict (id) do update set
          name = excluded.name, description = excluded.description, source = excluded.source,
          licence = excluded.licence, word_count = excluded.word_count, updated_at = excluded.updated_at, deleted_at = null;

        """
        for batch in SyncMerge.batches(entries, size: batchSize) {
            sql += """

            insert into public.words (headword, display, phonetic, translation_zh, definition_en, pos, collins, oxford, tags, bnc, frq, exchange)
            values

            """
            sql += batch.map(wordRow).joined(separator: ",\n")
            sql += """

            on conflict (headword) do update set
              display = excluded.display, phonetic = excluded.phonetic, translation_zh = excluded.translation_zh,
              definition_en = excluded.definition_en, pos = excluded.pos, collins = excluded.collins, oxford = excluded.oxford,
              tags = excluded.tags, bnc = excluded.bnc, frq = excluded.frq, exchange = excluded.exchange;

            """
        }
        for (batchIndex, batch) in SyncMerge.batches(entries, size: batchSize).enumerated() {
            let rows = batch.enumerated().map { offset, entry in
                "  (\(literal(entry.headword)), \(batchIndex * batchSize + offset + 1))"
            }
            sql += """

            insert into public.book_entries (id, book_id, position, headword, word_id)
            select md5(\(literal(book.slug + "/")) || v.headword)::uuid, \(literal(book.id.uuidString.lowercased()))::uuid, v.position, w.headword, w.id
            from (values
            \(rows.joined(separator: ",\n"))
            ) as v (headword, position)
            join public.words w on w.headword = v.headword
            on conflict (id) do update set position = excluded.position, word_id = excluded.word_id, deleted_at = null, updated_at = now();

            """
        }
        return sql
    }

    static func wordRow(_ entry: WordEntry) -> String {
        let fields = [
            literal(entry.headword), literal(entry.display), literal(entry.phonetic), literal(entry.translation),
            literal(entry.definition), literal(entry.posMix), String(entry.collins), entry.oxford ? "true" : "false",
            arrayLiteral(entry.tags), entry.bnc.map(String.init) ?? "null", entry.frq.map(String.init) ?? "null",
            literal(entry.exchange),
        ]
        return "  (" + fields.joined(separator: ", ") + ")"
    }

    /// A SQL string literal. Text with line breaks or backslashes uses an escape string (`E'…'`) so each
    /// row stays on one line.
    static func literal(_ text: String) -> String {
        if text.contains("\n") || text.contains("\\") || text.contains("\r") {
            let escaped = text.replacingOccurrences(of: "\\", with: "\\\\")
                .replacingOccurrences(of: "'", with: "''")
                .replacingOccurrences(of: "\r", with: "")
                .replacingOccurrences(of: "\n", with: "\\n")
            return "E'\(escaped)'"
        }
        return "'" + text.replacingOccurrences(of: "'", with: "''") + "'"
    }

    /// `'{gk,cet4,ky}'`; tags are plain letters and digits, anything else is dropped.
    static func arrayLiteral(_ items: [String]) -> String {
        let safe = items.filter { !$0.isEmpty && $0.unicodeScalars.allSatisfy { $0.isASCII && CharacterSet.alphanumerics.contains($0) } }
        return "'{" + safe.joined(separator: ",") + "}'"
    }
}
