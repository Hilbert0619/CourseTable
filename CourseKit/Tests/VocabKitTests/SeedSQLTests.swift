import Foundation
import Testing
@testable import VocabKit

@Suite struct SeedSQLTests {
    @Test func literals() {
        #expect(SeedSQL.literal("abandon") == "'abandon'")
        #expect(SeedSQL.literal("o'clock") == "'o''clock'")
        #expect(SeedSQL.literal("vt. 放弃\nn. 放任") == "E'vt. 放弃\\nn. 放任'")
        #expect(SeedSQL.literal("a\\b") == "E'a\\\\b'")
        #expect(SeedSQL.literal("it's\r\nfine") == "E'it''s\\nfine'")
        #expect(SeedSQL.literal("") == "''")
        #expect(SeedSQL.arrayLiteral(["gk", "cet4", "ky", "bad,tag", "", "x}"]) == "'{gk,cet4,ky}'")
        #expect(SeedSQL.arrayLiteral([]) == "'{}'")
    }

    @Test func wordRows() {
        let abandon = VocabFixture.sampleEntries.first { $0.headword == "abandon" }!
        #expect(SeedSQL.wordRow(abandon) == """
          ('abandon', 'abandon', 'ә''bændәn', E'vt. 放弃, 抛弃, 遗弃, 使屈从, 沉溺, 放纵\\nn. 放任, 无拘束, 狂热', \
        E'n. the trait of lacking restraint\\nv. forsake, leave behind', '', 3, true, '{gk,cet4,cet6,ky,toefl,gre}', \
        2057, 2182, 'd:abandoned/p:abandoned/i:abandoning/3:abandons')
        """)
        let bare = WordEntry(headword: "x", translation: "n. x")
        #expect(SeedSQL.wordRow(bare) == "  ('x', 'x', '', 'n. x', '', '', 0, false, '{}', null, null, '')")
    }

    @Test func migration() {
        let entries = (1...1201).map { WordEntry(headword: "w\($0)", translation: "n. 词\($0)") }
        let sql = SeedSQL.migration(for: .kaoyan, entries: entries)
        #expect(sql.hasPrefix("-- Generated by `vocab-content sql` from content/kaoyan-ecdict.csv."))
        #expect(sql.components(separatedBy: "insert into public.books").count == 2)
        #expect(sql.components(separatedBy: "insert into public.words").count == 4)  // 500 + 500 + 201
        #expect(sql.components(separatedBy: "insert into public.book_entries").count == 4)
        #expect(sql.contains("'00000000-0000-4000-8000-000000000001'::uuid, null, '考研词汇 (ECDICT)'"))
        #expect(sql.contains(", 1201, now())"))
        #expect(sql.contains("  ('w1', 1)"))
        #expect(sql.contains("  ('w501', 501)"))
        #expect(sql.contains("  ('w1201', 1201)"))
        #expect(sql.contains("md5('kaoyan-ecdict/' || v.headword)::uuid"))
        #expect(!sql.contains("\r"))
    }
}
